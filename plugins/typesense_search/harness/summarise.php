<?php

// Condense the battery outputs in results/ab/ into results/summary.md (one row per case) and
// results/verdicts.json (label => verdict, for the planning repository's coverage check).
// Usage: php summarise.php

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

$out = "# Battery results, one row per case\n\n"
    . "Generated by `summarise.php` from `results/ab/`. Counts are the number of resources returned. \"Not consulted\"\n"
    . "means core returned before asking the plugin; \"not run\" means the plugin has no search hook yet; \"declined\"\n"
    . "means the plugin fell back to core with the reason shown.\n";
$verdicts = array();

$cell = function (string $text): string {
    return str_replace(array('|', "\n"), array('\|', ' '), $text);
};

foreach (glob(__DIR__ . '/results/ab/*.txt') as $file) {
    $battery = basename($file, '.txt');
    $text = file_get_contents($file);
    $rows = array();

    preg_match_all('/^CHECK (?<label>[^:]+): (?<verdict>ok|FAIL)(?<detail>[^\n]*)$/m', $text, $checks, PREG_SET_ORDER);
    foreach ($checks as $c) {
        $rows[] = array($c['label'], '', '', '', '', ($c['verdict'] === 'ok' ? 'PASS' : 'FAIL') . trim($c['detail']));
        $verdicts[$battery][$c['label']] = $c['verdict'] === 'ok' ? 'PASS' : 'FAIL';
    }

    preg_match_all(
        '/^(?<label>[^\n]+?):  (?<search>"(?:[^"\\\\]|\\\\.)*")(?<opts>  \[[^\n]*\])?\n    core:   (?<core>[^\n]*)\n    plugin: (?<plugin>[^\n]*)\n    => (?<verdict>[^\n]*)/m',
        $text,
        $cases,
        PREG_SET_ORDER
    );
    foreach ($cases as $c) {
        $core = preg_match('/^total=(\d+)/', $c['core'], $m) ? $m[1]
            : (preg_match('/^non-array result (.*)$/', $c['core'], $m) ? 'no results, returns ' . $m[1] : $c['core']);
        if (strpos($c['plugin'], 'served') === 0) {
            $plugin = preg_match('/total=(\d+)/', $c['plugin'], $m) ? $m[1] : 'served';
        } elseif (strpos($c['plugin'], 'declined') === 0) {
            $plugin = $c['plugin'];
        } elseif (strpos($c['plugin'], 'not consulted') === 0) {
            $plugin = 'not consulted';
        } elseif (strpos($c['plugin'], 'not run') === 0) {
            $plugin = 'not run';
        } else {
            $plugin = $c['plugin'];
        }
        $rows[] = array($c['label'], json_decode($c['search']) ?? $c['search'], trim($c['opts'] ?? '', ' []'), $core, $plugin, $c['verdict']);
        $verdicts[$battery][$c['label']] = strpos($c['verdict'], 'PASS') === 0 ? 'PASS' : 'FAIL';
    }

    if (count($rows) === 0) {
        continue;
    }
    preg_match('/^RESULT: .*$/m', $text, $result);
    $out .= "\n## " . $battery . "\n\n" . ($result[0] ?? 'no RESULT line: the battery did not finish') . "\n\n| Case | Search | Arguments | Core | Plugin | Result |\n|---|---|---|---|---|---|\n";
    foreach ($rows as $r) {
        $out .= '| ' . $cell($r[0]) . ' | ' . ($r[1] === '' ? '' : '`' . $cell($r[1]) . '`') . ' | ' . $cell($r[2]) . ' | ' . $cell($r[3]) . ' | ' . $cell($r[4]) . ' | ' . $cell($r[5]) . " |\n";
    }
}

file_put_contents(__DIR__ . '/results/summary.md', $out);
file_put_contents(__DIR__ . '/results/verdicts.json', json_encode($verdicts, JSON_PRETTY_PRINT) . "\n");
echo 'wrote results/summary.md (' . substr_count($out, "\n| ") . " rows) and results/verdicts.json\n";
